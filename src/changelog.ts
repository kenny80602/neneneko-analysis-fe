// 機械地列出來會有三十行噪音，真正的變動被淹掉。
//
// 版本號格式 `YYYYMMDD-X`：同一天第二次上線就把字母往後推（A、B、C…）。不用 semver，
// 這個站台沒有對外的 API 相容性要維護，日期比「1.4.0」更能回答使用者想問的「這是哪天改的」。

